def to_index(type_id: int) -> int:
    """Map an xView type_id to a class index 0-59, or -1 if it is not a class."""
    if 0 <= type_id < len(XVIEW_CLASS2INDEX):
        return XVIEW_CLASS2INDEX[type_id]
    return -1
